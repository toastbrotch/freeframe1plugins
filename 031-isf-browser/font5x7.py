order = "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ"
assert len(order)==36
for ch in order:
    rows = font[ch]
    assert len(rows)==7 and all(len(r)==5 for r in rows), ch

def rowval(r):
    return int(r,2)  # col0 = MSB (leftmost), matches int(binary) natural order

lines_hi=[]
lines_lo=[]
for idx,ch in enumerate(order):
    rows = font[ch]
    hi = 0
    for i in range(4):        # rows 0..3
        hi += rowval(rows[i]) << (5*i)
    lo = 0
    for i in range(3):        # rows 4..6
        lo += rowval(rows[4+i]) << (5*i)
    assert hi < 2**24 and lo < 2**24
    lines_hi.append((idx,ch,hi))
    lines_lo.append((idx,ch,lo))

print("-- HI (rows 0-3) --")
for idx,ch,v in lines_hi:
    op = "if" if idx==0 else "else if"
    cond = f"ch < {idx}.5" if idx < 35 else "true"
    print(f"    {op} (ch < {idx+1}.0) return {v}.0; // '{ch}'")

print()
